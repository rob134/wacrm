placeholder_re = re.compile(r"(\{[^{}]+\}|<[^>]+>|</[^>]+>)")


def safe_translate(text: str) -> str:
    text = text.strip()
    if not text:
        return text
    if text in manual:
        return manual[text]

    if "{count, plural" in text or "{count, select" in text or "plural," in text or "select," in text:
        return text

    if placeholder_re.search(text):
        parts = re.split(r"(\{[^{}]+\}|<[^>]+>|</[^>]+>)", text)
        translated = []
        for part in parts:
            if not part:
                continue
            if placeholder_re.fullmatch(part):
                translated.append(part)
            elif part in manual:
                translated.append(manual[part])
            else:
                try:
                    translated_value = translator.translate(part)
                    translated.append(translated_value if translated_value is not None else part)
                except Exception:
                    translated.append(part)
        return "".join(translated)

    try:
        translated_value = translator.translate(text)
        return translated_value if translated_value is not None else text
    except Exception:
        return text


def walk(node):
    if isinstance(node, dict):
        return {key: walk(value) for key, value in node.items()}
    if isinstance(node, list):
        return [walk(value) for value in node]
    if isinstance(node, str):
        return safe_translate(node)
    return node

